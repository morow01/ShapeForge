import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../src/ui/attachmentPreviews.ts',import.meta.url),'utf8');
const parsed=ts.createSourceFile('previews.ts',source,ts.ScriptTarget.Latest,true);
const noImports=parsed.statements.filter(n=>!ts.isImportDeclaration(n)).map(n=>n.getFullText(parsed)).join('');
const js=ts.transpile(noImports,{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS});
const cached=new Map();let reads=0, remoteLoads=0;
const api=new Function('exports','attachmentBytes','attachmentPreview','saveAttachmentPreview',js+'; return exports;')({},async()=>{reads++;return undefined;},async id=>cached.get(id),async(id,data)=>cached.set(id,data));
for(const name of ['part.STL','template.3mf','manual.PDF','notes.txt','photo.png'])assert.equal(api.supportsPreview(name),true);
assert.equal(api.supportsPreview('archive.zip'),false);
const remote={id:'remote',name:'manual.pdf',size:100,driveId:'drive-id'};
assert.equal(await api.previewAttachment(remote),null,'opening the folder does not download original files');
assert.equal(remoteLoads,0);
cached.set('remote','data:image/png;base64,cached');
assert.equal(await api.previewAttachment({...remote,name:'Renamed manual.pdf'}),'data:image/png;base64,cached');
assert.equal(reads,1,'a rename reuses the cached preview without reading the original');
await assert.rejects(api.previewAttachment({...remote,id:'huge',size:200*1024*1024},async()=>{remoteLoads++;return new ArrayBuffer(1);}),/larger than/);
assert.equal(remoteLoads,0,'oversize original files are never fetched just for a preview');
console.log('File preview checks passed: supported formats, cached renames, lazy remote access, large-file limits.');
